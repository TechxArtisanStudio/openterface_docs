/**
 * Parse config/locales.yml nav_translations into JSON for sidebar.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { parse as parseYaml } from 'yaml';

const ROOT = path.resolve(import.meta.dirname, '..');
const LOCALES = path.join(ROOT, 'config/locales.yml');
const OUT = path.join(ROOT, 'src/config/nav-translations.generated.ts');

const locales = parseYaml(fs.readFileSync(LOCALES, 'utf8'), { uniqueKeys: false });

const byLocale = {};
for (const entry of locales) {
  byLocale[entry.locale] = entry.nav_translations ?? {};
}

const body = `// AUTO-GENERATED by scripts/load-nav-translations.mjs — do not edit.

import type { SiteLocale } from '../lib/locale';

export const NAV_TRANSLATIONS: Partial<Record<SiteLocale, Record<string, string>>> = ${JSON.stringify(byLocale, null, 2)};

export function translateNavLabel(label: string, locale: SiteLocale): string {
  if (locale === 'en') return label;
  const aliases: Record<string, string> = {
    'KVM-Go Series': 'KVM-Go Series ⏳',
    'KeyMod Series': 'KeyMod Series 🤘',
    'uConsole KVM Extension': 'uConsole KVM Extension 🛠️',
  };
  const key = NAV_TRANSLATIONS[locale]?.[label]
    ? label
    : aliases[label] ?? label;
  return NAV_TRANSLATIONS[locale]?.[key] ?? NAV_TRANSLATIONS[locale]?.[label] ?? label;
}
`;

fs.writeFileSync(OUT, body);
console.log(`Wrote nav translations for ${Object.keys(byLocale).length} locales`);
